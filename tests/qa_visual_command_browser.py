    def test_redraw_decodes_and_is_shared_by_large_small_and_map_displays(self):
        self.load({'prefs':{'showBoot':False},'evas':[{'state':'DEPLOYED','umbilical':True} for _ in range(3)]})
        self.open('eva')
        drawing=self.page.locator('.eva-redrawn').evaluate('(e)=>getComputedStyle(e).backgroundImage')
        self.assertTrue(drawing.startswith('url("data:image/png;base64,'))
        size=self.page.evaluate('''async image => {const i=new Image();i.src=image.slice(5,-2);await i.decode();return [i.naturalWidth,i.naturalHeight]}''',drawing)
        self.assertEqual(size,[1536,1024])
        positions=[]
        for unit in range(3):
            self.page.locator(f'[data-eva="{unit}"]').click()
            positions.append(self.page.locator('.eva-redrawn').evaluate('(e)=>getComputedStyle(e).backgroundPosition'))
            self.assertIn('UNIT-0'+str(unit),self.page.locator('[data-command-stream=eva]').get_attribute('data-message'))
            self.assertGreater(self.page.locator('.eva-redrawn').bounding_box()['height'],300)
            for selector in ['.eva-redrawn','.mechanism-eva',f'#canvasEva{unit} .eva-sprite']:
                self.assertEqual(self.page.locator(selector).first.evaluate('(e)=>getComputedStyle(e).backgroundImage'),drawing)
            self.page.screenshot(path=str(RESULTS/f'redraw-unit-{unit}.png'),full_page=True)
        self.assertEqual(len(set(positions)),3)
        self.assertEqual(self.page.locator('.eva-front-main,.eva-triptych-bg,.eva-painted').count(),0)

