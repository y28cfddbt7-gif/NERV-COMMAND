    def test_weather_uses_current_location_first_and_centers_local_radar(self):
        self.page.add_init_script('''window.fixtureGeoCalls=0;Object.defineProperty(navigator,'geolocation',{value:{getCurrentPosition(ok){window.fixtureGeoCalls++;ok({coords:{latitude:43.06,longitude:141.35}})}}});''')
        def weather_route(route):
            route.fulfill(json={'latitude':43.06,'longitude':141.35,'current':{'temperature_2m':12,'weather_code':0,'time':'2026-10-17T10:00'},'hourly':{'time':[]}})
        self.page.route('https://api.open-meteo.com/v1/forecast?**',weather_route)
        self.load({'prefs':{'showBoot':False,'autoWeather':False},'weather':{'raw':{'current':{'temperature_2m':30},'hourly':{},'latitude':35,'longitude':139},'position':{'lat':35,'lon':139},'place':'以前の現在地','updated':int(time.time()*1000)}})
        self.assertEqual(self.page.evaluate('window.fixtureGeoCalls'),0)
        self.open('weather')
        self.page.wait_for_function('NERV_TEST.getState().weather?.position?.lat===43.06')
        self.assertEqual(self.page.evaluate("NERV_MOBILE.view('weather')"),'current')
        self.assertEqual(self.page.locator('#wxLocation').inner_text(),'現在地')
        self.assertEqual(self.page.locator('#wxTemp').inner_text(),'12')
        self.assertEqual(self.page.locator('[data-radar-region="me"]').get_attribute('class'),'meteo-chip active')
        self.assertIn('現在地',self.page.locator('#meteoMapMark').inner_text())
        self.assertFalse(self.state()['prefs']['autoWeather'],'A successful manual/entry fetch must not change the setting')
        self.assertEqual(self.page.evaluate('window.fixtureGeoCalls'),1)
        self.open('home');self.open('weather');self.page.wait_for_timeout(150)
        self.assertEqual(self.page.evaluate('window.fixtureGeoCalls'),1)

